    private void buttonIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonIngresarActionPerformed
        String username = textFieldUsername.getText();
        String password = passwordField.getText();
        
        try(Connection con = Conexion.getConnection()) {
            EmpleadoDAO dao = new EmpleadoDAO(con);
            EmpleadoSesion sesion = dao.iniciarSesion(username, password);

            switch (sesion.puestoEmpleado()) {
                case Puesto.CAJERO -> {
                    this.dispose();
                    new Cajero(sesion.username()).setVisible(true);
                }
                case Puesto.COCINERO -> {
                    this.dispose();
                    new Cocinero(sesion.username()).setVisible(true);
                }
                case Puesto.GERENTE -> {
                    this.dispose();
                    new Gerente(sesion.nombreEmpleado()).setVisible(true);
                }
                case Puesto.MESERO -> {
                    this.dispose();
                    new Mesero(sesion.username()).setVisible(true);
                }
            }
        }
        catch (Exception e) {
            System.out.println(e.getMessage());
        }
    }//GEN-LAST:event_buttonIngresarActionPerformed

