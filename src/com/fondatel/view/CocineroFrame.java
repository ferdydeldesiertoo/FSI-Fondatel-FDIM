    private void cargarComandas() {
        try (Connection con = ConexionBD.getConnection()) {
            ComandaDAO dao = new ComandaDAO(con);
            List<Comanda> comandas = dao.leerTodos();
            llenarTabla(comandas);
        } catch (Exception ex) {
            System.out.println("Error al cargar comandas: " + ex.getMessage());
        }
    }

    private void llenarTabla(List<Comanda> lista) {
        ModeloTablaSoloLectura modelo = new ModeloTablaSoloLectura(
                new String[]{"Folio", "Fecha y Hora", "Observaciones", "Estado", "Alimento",
                        "Descripción"}, 0
        );

        for (Comanda item : lista) {
            modelo.addRow(new Object[]{
                    item.folio(),
                    item.fechaHora().format(FORMATO_FECHA),
                    item.observaciones(),
                    item.estadoOrden(),
                    item.nombreAlimento(),
                    item.descripcion()
            });
        }
        tableComandas.setModel(modelo);
        tableComandas.setRowHeight(30);
    }

