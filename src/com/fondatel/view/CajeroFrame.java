    private void cargarTickets() {
        try (Connection con = ConexionBD.getConnection()) {
            TicketDAO dao = new TicketDAO(con);
            List<Ticket> pedidos = dao.leerTodos();
            llenarTabla(pedidos);
        } catch (Exception ex) {
            System.out.println("Error al cargar tickets: " + ex.getMessage());
        }
    }

    private void llenarTabla(List<Ticket> lista) {
        ModeloTablaSoloLectura modelo = new ModeloTablaSoloLectura(
                new String[]{"Folio", "Fecha y Hora", "Silla", "Mesa", "Cliente",
                        "Mesero", "Alimento", "Precio"}, 0
        );

        for (Ticket item : lista) {
            modelo.addRow(new Object[]{
                    item.folio(),
                    item.fechaHora().format(FORMATO_FECHA),
                    item.silla(),
                    item.numeroMesa(),
                    item.nombreCliente(),
                    item.nombreEmpleado(),
                    item.nombreAlimento(),
                    String.format("$%.2f", item.precio())
            });
        }
        tableTickets.setModel(modelo);
        tableTickets.setRowHeight(30);
    }

