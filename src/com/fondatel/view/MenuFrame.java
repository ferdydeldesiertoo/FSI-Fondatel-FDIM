    private void cargarDatosIniciales() {
        try (Connection con = ConexionBD.getConnection()) {
            List<Menu> menu = new MenuDAO(con).leerTodos();
            llenarTabla(menu);
        } catch (Exception ex) {
            System.out.println("Error al cargar menu: " + ex.getMessage());
        }
    }

    private void llenarTabla(List<Menu> lista) {
        ModeloTablaSoloLectura modelo = new ModeloTablaSoloLectura(
                new String[]{"Nombre", "Descripción", "Precio", "Foto", "Categoría"}, 0
        ) {
            @Override
            public Class<?> getColumnClass(int columnIndex) {
                return columnIndex == 3 ? ImageIcon.class : Object.class;
            }
        };

        for (Menu item : lista) {
            ImageIcon iconoFinal = null;
            byte[] fotoBytes = item.foto();
            if (fotoBytes != null && fotoBytes.length > 0) {
                Image imagenEscalada = new ImageIcon(fotoBytes).getImage()
                        .getScaledInstance(60, 60, Image.SCALE_SMOOTH);
                iconoFinal = new ImageIcon(imagenEscalada);
            }
            modelo.addRow(new Object[]{
                    item.nombreAlimento(),
                    item.descripcion(),
                    String.format("$%.2f", item.precio()),
                    iconoFinal,
                    item.categoria()
            });
        }
        tableMenu.setModel(modelo);
        tableMenu.setRowHeight(60);
    }

    private void configurarComboCategoria() {
        DefaultComboBoxModel<Categoria> modeloCombo = new DefaultComboBoxModel<>();
        modeloCombo.addElement(null);
        for (Categoria cat : Categoria.values()) {
            modeloCombo.addElement(cat);
        }
        comboBoxCategoria.setModel(modeloCombo);

        comboBoxCategoria.setRenderer(new DefaultListCellRenderer() {
            @Override
            public Component getListCellRendererComponent(JList<?> list, Object value, int index, boolean isSelected, boolean cellHasFocus) {
                super.getListCellRendererComponent(list, value, index, isSelected, cellHasFocus);
                if (value == null) {
                    setText("Todas");
                }
                return this;
            }
        });
    }

