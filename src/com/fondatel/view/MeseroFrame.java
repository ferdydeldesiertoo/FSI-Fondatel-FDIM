    private void cargarPedidos() {
        try (Connection con = ConexionBD.getConnection()) {
            PedidoDAO dao = new PedidoDAO(con);
            List<Pedido> pedidos = checkBoxPedidos.isSelected()
                    ? dao.leerPorMesero(empleadoSesion.codigoEmpleado())
                    : dao.leerTodos();
            llenarTabla(pedidos);
        } catch (Exception ex) {
            logger.severe("Error al cargar pedidos: " + ex.getMessage());
        }
    }

    private void llenarTabla(List<Pedido> lista) {
        ModeloTablaSoloLectura modelo = new ModeloTablaSoloLectura(
                new String[]{"Folio", "Fecha y Hora", "Silla", "Mesa", "Cliente",
                        "Mesero", "Alimento", "Precio", "Observaciones", "Estado"}, 0
        );

        for (Pedido item : lista) {
            modelo.addRow(new Object[]{
                    item.folio(),
                    item.fechaHora().format(FORMATO_FECHA),
                    item.silla(),
                    item.numeroMesa(),
                    item.nombreCliente(),
                    item.nombreEmpleado(),
                    item.nombreAlimento(),
                    String.format("$%.2f", item.precio()),
                    item.observaciones(),
                    item.estadoOrden()
            });
        }
        tablePedidos.setModel(modelo);
        tablePedidos.setRowHeight(30);
    }

