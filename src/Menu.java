    private void cargarTablaAlimentos() {
        ModeloTablaSoloLectura modelo = new ModeloTablaSoloLectura(
                new String[]{"Nombre", "Descripcion", "Precio", "Foto", "Categoría"}, 0
        ) {
            @Override
            public Class<?> getColumnClass(int columnIndex) {
                if (columnIndex == 3) {
                    return ImageIcon.class;
                }
                return Object.class;
            }
        };

        try (Connection con = Conexion.getConnection()) {
            MenuDAO dao = new MenuDAO(con);
            menu = dao.leerTodos();

            for (com.app.model.Menu elemento_menu : menu) {
                System.out.println(elemento_menu.getCategoria());
                ImageIcon iconoOriginal = new ImageIcon(elemento_menu.getFoto());
                Image imagenEscalada = iconoOriginal.getImage().getScaledInstance(60, 60, Image.SCALE_SMOOTH);
                ImageIcon iconoFinal = new ImageIcon(imagenEscalada);

                modelo.addRow(new Object[]{
                        elemento_menu.getNombreAlimento(),
                        elemento_menu.getDescripcion(),
                        elemento_menu.getPrecio(),
                        iconoFinal,
                        elemento_menu.getCategoria()
                });
            }
        } catch (Exception ex) {
            System.out.println("Error al cargar alimentos: " + ex.getMessage());
        }

        tableMenu.setModel(modelo);
        tableMenu.setRowHeight(60);
    }

