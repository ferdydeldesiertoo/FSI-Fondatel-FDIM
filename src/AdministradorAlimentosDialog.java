    private void buttonCargarImagenActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonCargarImagenActionPerformed
        JFileChooser fc = new JFileChooser(System.getProperty("user.dir"));
        if(fc.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
            File archivo = fc.getSelectedFile();
            Image imagen = new ImageIcon(archivo.getPath()).getImage();
            Image imagenEscalada = imagen.getScaledInstance(fotoAlimento.getWidth(), fotoAlimento.getHeight(), Image.SCALE_SMOOTH);
            fotoAlimento.setIcon(new ImageIcon(imagenEscalada));
        }
    }//GEN-LAST:event_buttonCargarImagenActionPerformed

    private void buttonAgregarAlimentoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonAgregarAlimentoActionPerformed
        String nombre = textFieldNombre.getText();
        String descripcion = textAreaDescripcion.getText();
        double precio = Double.parseDouble(textFieldPrecio.getText());
        Categoria categoria = (Categoria) comboBoxCategoria.getSelectedItem();
        EstadoAlimento estado = (EstadoAlimento) comboBoxEstado.getSelectedItem();

        Alimento nuevoAlimento = new Alimento(nombre, descripcion, precio,
                convertirLabelABytes(fotoAlimento), categoria, estado);

        try(Connection con = Conexion.getConnection()) {
            AlimentoDAO dao = new AlimentoDAO(con);
            dao.insertar(nuevoAlimento);
            cargarTablaAlimentos();
        }
        catch(Exception e) {
            System.out.println("Error al insertar nuevo alimento: " + e.getMessage());
        }
    }//GEN-LAST:event_buttonAgregarAlimentoActionPerformed

    public byte[] convertirLabelABytes(JLabel label) {
        Icon icono = label.getIcon();

        if (icono == null) {
            return null;
        }

        BufferedImage bufferedImage = new BufferedImage(
                icono.getIconWidth(),
                icono.getIconHeight(),
                BufferedImage.TYPE_INT_RGB
        );

        Graphics2D g2d = bufferedImage.createGraphics();
        g2d.drawImage(((ImageIcon) icono).getImage(), 0, 0, null);
        g2d.dispose();

        try (ByteArrayOutputStream baos = new ByteArrayOutputStream()) {
            ImageIO.write(bufferedImage, "jpg", baos);
            return baos.toByteArray();
        } catch (IOException e) {
            e.printStackTrace();
            return null;
        }
    }

