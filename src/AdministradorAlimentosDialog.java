    private void cargarTablaAlimentos() {
        ModeloTablaSoloLectura modelo = new ModeloTablaSoloLectura(
                new String[]{"Id", "Nombre", "Descripcion", "Precio", "Foto", "Categoría", "Estado"}, 0
        ) {
            @Override
            public Class<?> getColumnClass(int columnIndex) {
                if (columnIndex == 4) {
                    return ImageIcon.class;
                }
                return Object.class;
            }
        };

        try (Connection con = Conexion.getConnection()) {
            AlimentoDAO dao = new AlimentoDAO(con);
            alimentos = dao.leerTodos();

            for (Alimento alimento : alimentos) {
                ImageIcon iconoOriginal = new ImageIcon(alimento.getFoto());
                Image imagenEscalada = iconoOriginal.getImage().getScaledInstance(60, 60, Image.SCALE_SMOOTH);
                ImageIcon iconoFinal = new ImageIcon(imagenEscalada);

                modelo.addRow(new Object[]{
                        alimento.getIdAlimento(),
                        alimento.getNombreAlimento(),
                        alimento.getDescripcion(),
                        alimento.getPrecio(),
                        iconoFinal,
                        alimento.getCategoria().name(),
                        alimento.getEstado()
                });
            }
        } catch (Exception ex) {
            System.out.println("Error al cargar alimentos: " + ex.getMessage());
        }

        tableAlimentos.setModel(modelo);
        tableAlimentos.setRowHeight(60);
    }

